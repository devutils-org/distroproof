//! Parsers tested on real files from several distros.

use std::io::Write;

use envprobe_core::parse::{kconfig, os_release, status};

macro_rules! fixture {
    ($path:literal) => {
        include_str!(concat!("fixtures/", $path))
    };
}

#[test]
fn os_release_distros() {
    // (fixture, ID, VERSION_ID, ID_LIKE, PRETTY_NAME)
    let cases = [
        (
            fixture!("os-release/debian-12"),
            "debian",
            Some("12"),
            None,
            "Debian GNU/Linux 12 (bookworm)",
        ),
        (
            fixture!("os-release/ubuntu-22.04"),
            "ubuntu",
            Some("22.04"),
            Some("debian"),
            "Ubuntu 22.04.4 LTS",
        ),
        (
            fixture!("os-release/rocky-9"),
            "rocky",
            Some("9.4"),
            Some("rhel centos fedora"),
            "Rocky Linux 9.4 (Blue Onyx)",
        ),
        (
            fixture!("os-release/alpine-3.20"),
            "alpine",
            Some("3.20.3"),
            None,
            "Alpine Linux v3.20",
        ),
        (
            fixture!("os-release/arch"),
            "arch",
            None,
            None,
            "Arch Linux",
        ),
        (
            fixture!("os-release/archarm-orbstack"),
            "archarm",
            None,
            Some("arch"),
            "Arch Linux ARM",
        ),
    ];
    for (text, id, version, like, pretty) in cases {
        let map = os_release::parse(text);
        assert_eq!(map["ID"], id);
        assert_eq!(map.get("VERSION_ID").map(String::as_str), version, "{id}");
        assert_eq!(map.get("ID_LIKE").map(String::as_str), like, "{id}");
        assert_eq!(map["PRETTY_NAME"], pretty);
    }
}

#[test]
fn kconfig_text() {
    let map = kconfig::parse(fixture!("kconfig/rocky-8-excerpt"));
    assert_eq!(map["CONFIG_BPF"], "y");
    assert_eq!(map["CONFIG_BPF_LSM"], "n");
    assert_eq!(map["CONFIG_DEFAULT_HOSTNAME"], "(none)");
    assert!(!map.contains_key("CONFIG_CC_VERSION_TEXT=\"gcc"));
    assert!(!map.contains_key("CONFIG_NOPE"));
}

#[test]
fn kconfig_gz_roundtrip() {
    let text = fixture!("kconfig/orbstack-arm64");
    let mut enc = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::default());
    enc.write_all(text.as_bytes()).unwrap();
    let gz = enc.finish().unwrap();
    let map = kconfig::parse_gz(&gz).unwrap();
    assert_eq!(map, kconfig::parse(text));
    assert_eq!(map["CONFIG_DEBUG_INFO_BTF"], "y");
    assert!(kconfig::parse_gz(b"not gzip").is_err());
}

#[test]
fn proc_status_variants() {
    let user = status::parse(fixture!("status/user"));
    assert_eq!(user.uids(), Some([1000; 4]));
    assert_eq!(user.cap_eff(), Some(0));
    assert_eq!(user.seccomp(), Some(0));
    assert_eq!(user.no_new_privs(), Some(false));

    let root = status::parse(fixture!("status/root"));
    assert_eq!(root.uids(), Some([0; 4]));
    assert_eq!(root.cap_eff(), Some(0x1ff_ffff_ffff));

    let docker = status::parse(fixture!("status/docker-root"));
    let caps = docker.cap_eff().unwrap();
    assert_eq!(docker.seccomp(), Some(2));
    // Docker keeps CAP_NET_RAW (13) but drops CAP_SYS_ADMIN (21) and CAP_BPF (39).
    assert_eq!((caps >> 13) & 1, 1);
    assert_eq!((caps >> 21) & 1, 0);
    assert_eq!((caps >> 39) & 1, 0);

    let sandboxed = status::parse(fixture!("status/sandboxed-user"));
    assert_eq!(sandboxed.no_new_privs(), Some(true));
    assert_eq!(sandboxed.seccomp(), Some(2));

    let broken = status::parse("Uid:\tabc\nCapEff:\tzz\n");
    assert_eq!(broken.uids(), None);
    assert_eq!(broken.cap_eff(), None);
    assert_eq!(broken.seccomp(), None);
}

#[test]
fn ldconfig_output() {
    let out = "1234 libs found in cache `/etc/ld.so.cache'\n\
        \tlibz.so.1 (libc6,x86-64) => /lib/x86_64-linux-gnu/libz.so.1\n\
        \tlibbpf.so.1 (libc6,x86-64) => /lib/x86_64-linux-gnu/libbpf.so.1\n\
        Cache generated by: ldconfig (GNU libc) stable release version 2.36\n";
    let entries = envprobe_core::parse::ldconfig::parse(out);
    assert_eq!(entries.len(), 2);
    assert_eq!(
        entries[1],
        (
            "libbpf.so.1".to_string(),
            "/lib/x86_64-linux-gnu/libbpf.so.1".to_string()
        )
    );
}

#[test]
fn probe_all_covers_every_category_without_panicking() {
    let names: Vec<String> = envprobe_core::probe_all()
        .into_iter()
        .map(|s| s.name)
        .collect();
    let expected: Vec<&str> = envprobe_core::section_names().collect();
    assert_eq!(names, expected);
    assert_eq!(names.len(), 20);
}
